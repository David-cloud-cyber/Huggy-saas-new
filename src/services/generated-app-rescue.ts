export type GeneratedRescueAppKind =
  | 'todo'
  | 'timer'
  | 'commerce'
  | 'booking'
  | 'dashboard'
  | 'finance'
  | 'ai_tool'
  | 'restaurant'
  | 'portfolio'
  | 'calculator'
  | 'notes'
  | 'quiz'
  | 'weather'
  | 'chat'
  | 'generic';

export type GeneratedRescueInput = {
  projectName?: string;
  prompt?: string;
};

export function extractActionablePromptText(value = '') {
  const source = String(value || '').trim();
  if (!source) return '';
  const buildRequest = source.match(/(?:build request|demande|requete|requête)\s*:\s*([\s\S]+)$/i)?.[1]?.trim();
  if (buildRequest && buildRequest.length > 12) return buildRequest;
  try {
    const parsed = JSON.parse(source);
    const candidates = [
      parsed?.prompt,
      parsed?.request,
      parsed?.build_request,
      parsed?.user_request,
      parsed?.message,
      parsed?.plan?.next_action,
      parsed?.plan?.title,
    ].filter(Boolean).map(String);
    const best = candidates.sort((a, b) => b.length - a.length)[0];
    if (best) return best;
  } catch {
    // Not a JSON object; continue with text cleanup.
  }
  return source
    .replace(/```(?:json|javascript|js)?[\s\S]*?```/gi, ' ')
    .replace(/\{\s*"plan"\s*:[\s\S]*?\}\s*/i, ' ')
    .replace(/\b(status|plan|steps|phase|details|message|next_action)\b\s*:\s*/gi, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

function normalizeInput(input: GeneratedRescueInput | string = {}, prompt = ''): Required<GeneratedRescueInput> {
  if (typeof input === 'string') {
    return {
      projectName: input || 'Huggy App',
      prompt: extractActionablePromptText(prompt || input || ''),
    };
  }
  return {
    projectName: input.projectName || 'Huggy App',
    prompt: extractActionablePromptText(input.prompt || input.projectName || ''),
  };
}

function sourceText(input: Required<GeneratedRescueInput>) {
  return `${input.projectName} ${input.prompt}`.toLowerCase();
}

function cleanTitle(value = '', fallback = 'Huggy App') {
  const clean = String(value || '').replace(/\s+/g, ' ').trim();
  if (!clean || /^untitled|huggy app$/i.test(clean)) return fallback;
  return clean.slice(0, 90);
}

function cleanSummary(value = '', fallback = 'A responsive web app generated by Huggy.') {
  const clean = extractActionablePromptText(value).replace(/\s+/g, ' ').trim();
  return (clean || fallback).slice(0, 180);
}

function literal(value: string) {
  return JSON.stringify(value);
}

function appConstants(input: Required<GeneratedRescueInput>, fallbackTitle: string, fallbackSummary: string) {
  return [
    `const appTitle = ${literal(cleanTitle(input.projectName, fallbackTitle))};`,
    `const appSummary = ${literal(cleanSummary(input.prompt, fallbackSummary))};`,
    '',
  ];
}

export function inferGeneratedRescueAppKind(input: GeneratedRescueInput | string = {}, prompt = ''): GeneratedRescueAppKind {
  const normalized = normalizeInput(input, prompt);
  const text = sourceText(normalized);
  if (/\b(calculator|calculatrice|calcul|arithmetic|operation|division|multiplication|soustraction|addition)\b/.test(text)) return 'calculator';
  if (/\b(quiz|qcm|questionnaire|exam|examen|test de connaissance|trivia)\b/.test(text)) return 'quiz';
  if (/\b(notes?|prise de notes?|note taking|notepad|memo|memos|memoire|markdown editor)\b/.test(text)) return 'notes';
  if (/\b(meteo|weather|forecast|previsions|temperature)\b/.test(text)) return 'weather';
  if (/\b(pomodoro|pomodero|minuteur|timer|countdown|chrono|focus session|short break|long break)\b/.test(text)) return 'timer';
  if (/\b(todo|to-do|to do|task|tasks|tache|taches|checklist|kanban|liste de taches|gestion de taches)\b/.test(text)) return 'todo';
  if (/\b(ecommerce|e-commerce|commerce|shop|store|cart|checkout|product|products|panier|boutique|catalogue|produit|payment|paiement)\b/.test(text)) return 'commerce';
  if (/\b(restaurant|menu|dish|table|chef|local business|business local|cafe|coffee|meal)\b/.test(text)) return 'restaurant';
  if (/\b(booking|reservation|appointment|calendar|slot|rendez-vous|rdv|calendrier|availability)\b/.test(text)) return 'booking';
  if (/\b(budget|finance|financial|expense|expenses|income|revenue|recette|recettes|depense|depenses|dépense|dépenses|solde|transaction|transactions|money|cashflow)\b/.test(text)) return 'finance';
  if (/\b(dashboard|admin|crm|analytics|metric|kpi|client|invoice|pipeline|portal|erp|backoffice|internal tool)\b/.test(text)) return 'dashboard';
  if (/\b(chat\b|messagerie|messenger|conversation app|im app|chat room)\b/.test(text)) return 'chat';
  if (/\b(ai tool|chatbot|assistant|prompt|generator|resume|summarize|rewrite|llm|outil ia|generateur ia)\b/.test(text)) return 'ai_tool';
  if (/\b(portfolio|agency|landing|one page|site vitrine|case study|contact form|personal site|creative)\b/.test(text)) return 'portfolio';
  return 'generic';
}

export function createGeneratedRescueAppTsx(input: GeneratedRescueInput | string = {}, prompt = '') {
  const normalized = normalizeInput(input, prompt);
  const kind = inferGeneratedRescueAppKind(normalized);
  if (kind === 'todo') return todoApp(normalized);
  if (kind === 'timer') return timerApp(normalized);
  if (kind === 'commerce') return commerceApp(normalized);
  if (kind === 'booking') return bookingApp(normalized);
  if (kind === 'finance') return financeApp(normalized);
  if (kind === 'dashboard') return dashboardApp(normalized);
  if (kind === 'ai_tool') return aiToolApp(normalized);
  if (kind === 'restaurant') return restaurantApp(normalized);
  if (kind === 'portfolio') return portfolioApp(normalized);
  if (kind === 'calculator') return calculatorApp(normalized);
  if (kind === 'notes') return notesApp(normalized);
  if (kind === 'quiz') return quizApp(normalized);
  if (kind === 'weather') return weatherApp(normalized);
  if (kind === 'chat') return chatApp(normalized);
  return genericApp(normalized);
}

