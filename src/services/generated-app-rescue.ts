    '        <div className="mt-4 grid grid-cols-4 gap-2">',
    '          {keys.map((key, idx) => (',
    '            <button key={idx} type="button" onClick={key.onClick}',
    '              className={(key.cls ?? "bg-slate-50") + " h-14 rounded-2xl text-lg font-semibold hover:opacity-90 active:scale-95 transition"}>',
    '              {key.label}',
    '            </button>',
