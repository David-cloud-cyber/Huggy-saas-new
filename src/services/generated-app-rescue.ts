    "    { label: '4', onClick: () => inputDigit('4') },",
    "    { label: '5', onClick: () => inputDigit('5') },",
    "    { label: '6', onClick: () => inputDigit('6') },",
    "    { label: '-', onClick: () => applyOp('-'), cls: 'bg-amber-500 text-white' },",
    "    { label: '1', onClick: () => inputDigit('1') },",
    "    { label: '2', onClick: () => inputDigit('2') },",
    "    { label: '3', onClick: () => inputDigit('3') },",
    "    { label: '+', onClick: () => applyOp('+'), cls: 'bg-amber-500 text-white' },",
    "    { label: '0', onClick: () => inputDigit('0') },",
    "    { label: '.', onClick: inputDot },",
    "    { label: '=', onClick: equals, cls: 'bg-emerald-500 text-white col-span-2' },",
    "  ];",
    '',
    '  return (',
    '    <main className="min-h-screen bg-slate-50 px-4 py-8 text-slate-950">',
    '      <section className="mx-auto max-w-sm rounded-3xl border border-slate-200 bg-white p-5 shadow-sm">',
