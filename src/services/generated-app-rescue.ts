    '  const [quantity, setQuantity] = useState(1);',
    "  const [feedback, setFeedback] = useState('Choose a product to start.');",
    '  const total = useMemo(() => cart.reduce((sum, item) => sum + item.price, 0) * quantity, [cart, quantity]);',
    '  function addToCart(product: Product) { setCart((current) => [{ ...product, variant }, ...current]); setFeedback(`${product.name} added to cart.`); }',
