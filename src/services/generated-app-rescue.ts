    '  function checkout() { if (!cart.length) { setFeedback("Your cart is empty."); return; } setFeedback(`Checkout ready for ${cart.length} item(s). Demo payment confirmation created.`); }',
    '',
    '  return (',
    '    <main className="min-h-screen bg-stone-50 px-4 py-8 text-stone-950 sm:px-6 lg:px-8">',
    '      <section className="mx-auto max-w-6xl">',
    '        <p className="mb-3 text-xs font-bold uppercase tracking-[0.22em] text-blue-600">Generated by Huggy</p>',
    '        <h1 className="text-4xl font-black tracking-tight sm:text-6xl">{appTitle}</h1>',
    '        <p className="mt-3 max-w-2xl text-stone-600">{appSummary}</p>',
    '        <div className="mt-6 flex flex-wrap gap-3">',
    '          <select className="rounded-full border border-stone-200 bg-white px-4 py-3" value={variant} onChange={(event) => setVariant(event.target.value)} aria-label="Variant"><option>Black</option><option>Blue</option><option>Steel</option></select>',
