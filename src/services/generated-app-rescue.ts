function timerApp(input: Required<GeneratedRescueInput>) {
  return [
    "import { useEffect, useMemo, useState } from 'react';",
    "import './index.css';",
    '',
    "type Mode = 'focus' | 'short' | 'long';",
    "const modes: Record<Mode, { label: string; seconds: number }> = { focus: { label: 'Focus', seconds: 25 * 60 }, short: { label: 'Short break', seconds: 5 * 60 }, long: { label: 'Long break', seconds: 15 * 60 } };",
    ...appConstants(input, 'Pomodoro timer', 'Run focus sessions, pause, reset and track completed cycles.'),
    'function formatTime(value: number) { return `${Math.floor(value / 60).toString().padStart(2, "0")}:${(value % 60).toString().padStart(2, "0")}`; }',
    '',
    'export default function App() {',
    "  const [mode, setMode] = useState<Mode>('focus');",
    '  const [seconds, setSeconds] = useState(modes.focus.seconds);',
    '  const [isRunning, setIsRunning] = useState(false);',
    '  const [cycles, setCycles] = useState(0);',
    "  const [feedback, setFeedback] = useState('Ready for a focus session.');",
    '  useEffect(() => {',
    '    if (!isRunning) return undefined;',
    '    const timer = window.setInterval(() => {',
    '      setSeconds((value) => {',
    '        if (value <= 1) {',
    '          setIsRunning(false);',
    '          setCycles((count) => count + 1);',
    "          setFeedback('Session complete. Choose the next mode.');",
    '          return modes[mode].seconds;',
    '        }',
    '        return value - 1;',
    '      });',
    '    }, 1000);',
    '    return () => window.clearInterval(timer);',
    '  }, [isRunning, mode]);',
    '  const progress = useMemo(() => Math.round(((modes[mode].seconds - seconds) / modes[mode].seconds) * 100), [mode, seconds]);',
    '  function switchMode(next: Mode) { setMode(next); setSeconds(modes[next].seconds); setIsRunning(false); setFeedback(`${modes[next].label} selected.`); }',
    '  function resetTimer() { setIsRunning(false); setSeconds(modes[mode].seconds); setFeedback("Timer reset."); }',
    '',
    '  return (',
    '    <main className="min-h-screen bg-slate-950 px-4 py-8 text-white sm:px-6 lg:px-8">',
    '      <section className="mx-auto max-w-3xl rounded-3xl border border-white/10 bg-white/10 p-6 shadow-2xl backdrop-blur sm:p-8" aria-label="Pomodoro timer">',
    '        <p className="mb-3 text-xs font-bold uppercase tracking-[0.22em] text-blue-300">Generated by Huggy</p>',
    '        <h1 className="text-3xl font-bold tracking-tight sm:text-5xl">{appTitle}</h1>',
    '        <p className="mt-3 text-blue-100">{appSummary}</p>',
    '        <div className="mt-6 rounded-[2rem] border border-white/10 bg-slate-900 p-8 text-center">',
    '          <strong className="block text-7xl font-black tracking-tight sm:text-8xl">{formatTime(seconds)}</strong>',
    '          <span className="mt-2 block text-blue-200">{modes[mode].label}</span>',
    '          <div className="mt-5 h-2 rounded-full bg-white/10"><span className="block h-full rounded-full bg-blue-400" style={{ width: `${progress}%` }} /></div>',
    '        </div>',
    '        <div className="mt-5 flex flex-wrap gap-2">',
    '          {(Object.keys(modes) as Mode[]).map((item) => <button key={item} className={mode === item ? "rounded-full bg-blue-400 px-4 py-2 text-sm font-bold text-slate-950" : "rounded-full border border-white/10 px-4 py-2 text-sm font-bold text-white transition hover:border-blue-300"} type="button" onClick={() => switchMode(item)}>{modes[item].label}</button>)}',
    '        </div>',
    '        <div className="mt-5 grid gap-3 sm:grid-cols-3">',
    '          <button className="rounded-full bg-white px-5 py-3 font-semibold text-slate-950" type="button" onClick={() => { setIsRunning(true); setFeedback("Timer running."); }}>Start</button>',
    '          <button className="rounded-full border border-white/10 px-5 py-3 font-semibold text-white" type="button" onClick={() => { setIsRunning(false); setFeedback("Paused."); }}>Pause</button>',
    '          <button className="rounded-full border border-white/10 px-5 py-3 font-semibold text-white" type="button" onClick={resetTimer}>Reset</button>',
    '        </div>',
    '        <p className="mt-4 rounded-2xl bg-blue-400/10 px-4 py-3 text-sm text-blue-100" role="status">{feedback} Cycles: {cycles}</p>',
    '      </section>',
    '    </main>',
    '  );',
    '}',
    '',
  ].join('\n');
}

