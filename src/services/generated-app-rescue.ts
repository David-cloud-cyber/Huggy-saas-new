    '            className="flex-1 rounded-full border border-slate-200 px-4 py-2" />',
    '          <button type="submit" disabled={loading} className="rounded-full bg-sky-600 px-5 py-2 font-semibold text-white disabled:opacity-40">',
    "            {loading ? 'Loading…' : 'Search'}",
    '          </button>',
    '        </form>',
    '        {error && <p className="mt-4 rounded-xl bg-rose-50 px-4 py-3 text-rose-700">{error}</p>}',
